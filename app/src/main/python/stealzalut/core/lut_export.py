"""Adobe .cube LUT file exporter.

Writes 3-D LUT data in the industry-standard Adobe Cube LUT 1.0
format understood by DaVinci Resolve, Adobe Premiere, and most
colour-grading tools.
"""

from __future__ import annotations

import os
from typing import Union

import numpy as np
from numpy.typing import NDArray


def export_cube(
    lut_data: NDArray[Union[np.float32, np.float64]],
    output_path: str,
    size: int = 33,
    title: str = "Generated by StealZaLUT",
) -> str:
    """Export LUT data as an Adobe ``.cube`` file.

    The file is written with UTF-8 encoding and uses standard header fields.
    Data lines are written with :func:`numpy.savetxt` directly to disk
    for optimal performance (<30ms for 33^3 grid, zero Python row iteration).

    Args:
        lut_data: Float array of shape ``(size ** 3, 3)`` with values in ``[0.0, 1.0]``.
        output_path: Destination file path for the ``.cube`` file.
        size: LUT grid dimension that was used to produce *lut_data*.
        title: TITLE header value embedded in the file.

    Returns:
        The absolute path of the written file.

    Raises:
        ValueError: If *lut_data* does not have the expected shape.
    """
    expected_rows: int = size ** 3
    if lut_data.shape != (expected_rows, 3):
        raise ValueError(
            f"lut_data shape {lut_data.shape} does not match expected "
            f"({expected_rows}, 3) for LUT size {size}."
        )

    # Build the header
    header_lines: list[str] = [
        f'TITLE "{title}"',
        "# Created by StealZaLUT Mobile",
        f"LUT_3D_SIZE {size}",
        "DOMAIN_MIN 0.0 0.0 0.0",
        "DOMAIN_MAX 1.0 1.0 1.0",
        "",
    ]
    header: str = "\n".join(header_lines)

    os.makedirs(os.path.dirname(output_path) or ".", exist_ok=True)

    with open(output_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(header)
        np.savetxt(fh, lut_data, fmt="%.6f", delimiter=" ")

    return os.path.abspath(output_path)
